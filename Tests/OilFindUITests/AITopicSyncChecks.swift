import Foundation
@testable import OilFindApp

func runSyncChecks(_ root: URL) throws {
    let directory = root.appendingPathComponent("sync-" + UUID().uuidString)
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    defer { try? FileManager.default.removeItem(at: directory) }
    let home = directory.appendingPathComponent("home")
    let project = home.appendingPathComponent(".claude/projects/demo")
    try FileManager.default.createDirectory(at: project, withIntermediateDirectories: true)
    try Data().write(to: project.deletingLastPathComponent().appendingPathComponent(".DS_Store"))
    let id = UUID().uuidString.lowercased(), url = project.appendingPathComponent("placeholder.jsonl")
    let file = url.deletingLastPathComponent().appendingPathComponent(id + ".jsonl")
    func line(_ text: String, role: String = "user") throws -> Data {
        var data = try JSONSerialization.data(withJSONObject: ["type":role,"cwd":"/demo/project","message":["content":text]])
        data.append(10); return data
    }
    var checks: [[String:Any]] = []
    func check(_ name: String, _ condition: Bool) throws {
        checks.append(["name":name,"passed":condition]); print("\(condition ? "PASS" : "FAIL") \(name)"); fflush(stdout)
        guard condition else { throw NSError(domain: name, code: 1) }
    }
    try line("测试检索新会话").write(to: file)
    let indexURL = directory.appendingPathComponent("index.sqlite")
    let index = try AITopicIndex(url: indexURL)
    let importer = AITopicIndexer(index: index, locations: .init(home: home))
    try importer.refresh()
    try check("首次导入保留标题与项目", try index.search("测试检索新会话").topics.first?.title == "测试检索新会话")
    let before = try index.search("").topics.first
    let began = CFAbsoluteTimeGetCurrent(); try importer.refresh()
    let refreshMS = (CFAbsoluteTimeGetCurrent() - began) * 1000
    let after = try index.search("").topics.first
    try check("未修改时重复刷新保留标题与项目", before?.title == after?.title && before?.project == after?.project)
    let reopened = try AITopicIndex(url: indexURL)
    try AITopicIndexer(index: reopened, locations: .init(home: home)).refresh()
    try check("重开索引后保留标题与项目", try reopened.search("").topics.first?.title == before?.title && reopened.search("").topics.first?.project == before?.project)
    let handle = try FileHandle(forWritingTo: file); try handle.seekToEnd()
    let append = try line("增量更新独特词", role: "assistant"), split = append.count / 2
    try handle.write(contentsOf: append.prefix(split)); try importer.refresh()
    try check("未写完的 JSON 不进入索引", try index.search("增量更新独特词").topics.isEmpty)
    try handle.write(contentsOf: append.dropFirst(split)); try handle.close()
    let updateBegan = CFAbsoluteTimeGetCurrent(); try importer.refresh()
    let updateMS = (CFAbsoluteTimeGetCurrent() - updateBegan) * 1000
    try check("写完后增量内容可以搜到", try index.search("增量更新独特词").topics.count == 1)
    try line("缩短替换").write(to: file); try importer.refresh()
    try check("日志缩短后撤下旧内容", try index.search("增量更新独特词").topics.isEmpty && index.search("缩短替换").topics.count == 1)
    let descriptorRoot = home.appendingPathComponent("Library/Application Support/Claude/claude-code-sessions/account")
    try FileManager.default.createDirectory(at: descriptorRoot, withIntermediateDirectories: true)
    let descriptor = descriptorRoot.appendingPathComponent("local.json")
    func register(_ title: String, archived: Bool = false) throws {
        try JSONSerialization.data(withJSONObject: ["sessionId":"local_" + id,"cliSessionId":id,"title":title,"cwd":"/demo/project","isArchived":archived]).write(to: descriptor)
    }
    try register(""); try importer.refresh(); try importer.refresh()
    try check("空桌面标题保留已提取的标题与项目", try index.search("").topics.first?.title == "缩短替换" && index.search("").topics.first?.project == "/demo/project")
    try register("桌面与终端共同话题"); try importer.refresh()
    try check("Claude 桌面与终端按 ID 去重", try index.search("").topics.count == 1 && index.search("").topics.first?.title == "桌面与终端共同话题")
    try register("桌面与终端共同话题", archived: true); try importer.refresh(); try importer.refresh()
    try check("Claude 归档后标题和正文均不可检索", try index.search("").topics.isEmpty && index.search("桌面与终端共同话题").topics.isEmpty && index.search("缩短替换").topics.isEmpty)
    try register("桌面与终端共同话题"); try importer.refresh()
    try check("Claude 取消归档恢复已有正文", try index.search("缩短替换").topics.count == 1)
    try FileManager.default.removeItem(at: file); try importer.refresh()
    try check("删除正文但保留桌面列表时撤下旧正文", try index.search("缩短替换").topics.isEmpty && index.search("桌面与终端共同话题").topics.count == 1)
    try register("改名后的桌面会话"); try importer.refresh()
    try check("桌面改名更新检索词", try index.search("桌面与终端共同话题").topics.isEmpty && index.search("改名后的桌面会话").topics.count == 1)
    try Data("{".utf8).write(to: descriptor); try importer.refresh()
    try check("暂时损坏的列表文件不触发误删", try index.search("改名后的桌面会话").topics.count == 1)
    try FileManager.default.removeItem(at: descriptor); try importer.refresh()
    try check("源会话删除后撤下搜索结果", try index.search("").topics.isEmpty)
    try line("权限检查保留正文").write(to: file); try importer.refresh()
    try FileManager.default.setAttributes([.posixPermissions: 0o000], ofItemAtPath: project.path)
    do { try importer.refresh() } catch {
        try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: project.path); throw error
    }
    try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: project.path)
    try check("目录暂时不可读时保留缓存", try index.search("权限检查保留正文").topics.count == 1)
    try Data().write(to: file); try importer.refresh()
    try check("日志被清空后撤下旧正文", try index.search("权限检查保留正文").topics.isEmpty)
    let prefix = try line(String(repeating: "padding-", count: 180), role: "assistant")
    var original = prefix; original.append(try line("旧尾标志")); try original.write(to: file); try importer.refresh()
    var replacement = prefix; replacement.append(try line("新尾标志内容比旧记录更长，保持头部内容一致"))
    let rewriteHandle = try FileHandle(forWritingTo: file); try rewriteHandle.write(contentsOf: replacement); try rewriteHandle.truncate(atOffset: UInt64(replacement.count)); try rewriteHandle.close(); try importer.refresh()
    try check("相同文件头且体积增大的重写会撤下旧正文", try index.search("旧尾标志").topics.isEmpty && index.search("新尾标志").topics.count == 1)
    try FileManager.default.removeItem(at: file); try importer.refresh()
    try check("普通目录元数据不妨碍删除同步", try index.search("").topics.isEmpty)

    let codex = home.appendingPathComponent(".codex")
    try FileManager.default.createDirectory(at: codex, withIntermediateDirectories: true)
    let state = try AITopicSQL(codex.appendingPathComponent("state_5.sqlite"))
    try state.run("CREATE TABLE threads(id TEXT PRIMARY KEY,title TEXT,name TEXT,cwd TEXT,updated_at REAL,rollout_path TEXT,archived INTEGER,thread_source TEXT,source TEXT,first_user_message TEXT)")
    let codexID = UUID().uuidString.lowercased(), subID = UUID().uuidString.lowercased()
    let row = try state.prepare("INSERT INTO threads VALUES(?,?,?,?,?,?,?,?,?,?)")
    row.bind([codexID,"首条提问而非显示名","桌面实际短标题","/demo/codex","1","","0","user","vscode",""]); _ = try row.next()
    let sub = try state.prepare("INSERT INTO threads VALUES(?,?,?,?,?,?,?,?,?,?)")
    sub.bind([subID,"内部子代理","内部子代理","/demo/codex","1","","0","subagent","subagent",""]); _ = try sub.next()
    let history = try AITopicSQL(codex.appendingPathComponent("thread_history_1.sqlite"))
    try history.run("CREATE TABLE thread_items(thread_id TEXT,item_id TEXT,item_type TEXT,item_json TEXT,rollout_ordinal INTEGER,updated_at_ordinal INTEGER,PRIMARY KEY(thread_id,item_id))")
    func historyMessage(_ key: String, _ text: String, _ ordinal: Int, _ update: Int) throws {
        let object = try JSONSerialization.data(withJSONObject: ["type":"agentMessage","text":text])
        let s = try history.prepare("INSERT INTO thread_items VALUES(?,?,?,?,?,?) ON CONFLICT(thread_id,item_id) DO UPDATE SET item_json=excluded.item_json,updated_at_ordinal=excluded.updated_at_ordinal")
        s.bind([codexID,key,"agentMessage",String(decoding: object, as: UTF8.self),String(ordinal),String(update)]); _ = try s.next()
    }
    try historyMessage("m1", "Codex原始正文独特词", 1, 1); try importer.refresh()
    try check("Codex 优先使用实际显示名并排除子代理", try index.search("").topics.count == 1 && index.search("").topics.first?.title == "桌面实际短标题")
    try importer.refresh()
    try check("Codex 重复刷新保留正文和标题", try index.search("Codex原始正文独特词").topics.first?.title == "桌面实际短标题")
    try state.run("UPDATE threads SET archived=1 WHERE thread_source='user'"); try importer.refresh(); try importer.refresh()
    try check("Codex 时间戳不变时归档也撤下结果", try index.search("").topics.isEmpty && index.search("桌面实际短标题").topics.isEmpty && index.search("Codex原始正文独特词").topics.isEmpty)
    try state.run("UPDATE threads SET archived=0 WHERE thread_source='user'"); try importer.refresh()
    try check("Codex 取消归档恢复已有正文", try index.search("Codex原始正文独特词").topics.count == 1)
    try state.run("UPDATE threads SET name='Codex修改后的名字',updated_at=2 WHERE thread_source='user'"); try importer.refresh()
    try check("Codex 改名撤下旧标题词", try index.search("桌面实际短标题").topics.isEmpty && index.search("Codex修改后的名字").topics.count == 1)
    try historyMessage("m2", "Codex追加消息独特词", 2, 2); try importer.refresh()
    try check("Codex 新增消息可检索", try index.search("Codex追加消息独特词").topics.count == 1)
    try historyMessage("m1", "Codex替换消息独特词", 1, 3); try importer.refresh()
    try check("Codex 原消息更新后撤下旧词", try index.search("Codex原始正文独特词").topics.isEmpty && index.search("Codex替换消息独特词").topics.count == 1)
    try historyMessage("m1", "", 1, 4); try importer.refresh()
    try check("Codex 空消息替换会撤下旧正文", try index.search("Codex替换消息独特词").topics.isEmpty)
    try history.run("DELETE FROM thread_items"); try importer.refresh()
    try check("Codex 删除正文消息会撤下旧内容", try index.search("Codex追加消息独特词").topics.isEmpty)
    let sessions = codex.appendingPathComponent("sessions")
    try FileManager.default.createDirectory(at: sessions, withIntermediateDirectories: true)
    let rollout = sessions.appendingPathComponent("rollout.jsonl")
    let meta = try JSONSerialization.data(withJSONObject: ["type":"session_meta","payload":["id":codexID,"cwd":"/demo/codex"]])
    try (meta + Data([10])).write(to: rollout)
    let staleBody = try JSONSerialization.data(withJSONObject: ["type":"response_item","payload":["type":"message","role":"assistant","content":[["type":"output_text","text":"遗留日志不能复活已删正文"]]]])
    try (meta + Data([10]) + staleBody + Data([10])).write(to: rollout)
    try importer.refresh()
    try check("canonical history 清空不回退遗留正文", try index.search("遗留日志不能复活已删正文").topics.isEmpty)
    try state.run("DELETE FROM threads WHERE thread_source='user'"); try importer.refresh()
    try check("Codex 删除话题后不被遗留日志复活", try index.search("").topics.isEmpty && index.search("Codex追加消息独特词").topics.isEmpty)

    let legacyHome = directory.appendingPathComponent("legacy")
    let legacySessions = legacyHome.appendingPathComponent(".codex/sessions")
    try FileManager.default.createDirectory(at: legacySessions, withIntermediateDirectories: true)
    let legacyFile = legacySessions.appendingPathComponent("legacy.jsonl")
    let legacyBody = try JSONSerialization.data(withJSONObject: ["type":"response_item","payload":["type":"message","role":"user","content":[["type":"input_text","text":"旧版会话可持续检索"]]]])
    try (meta + Data([10]) + legacyBody + Data([10])).write(to: legacyFile)
    let legacyIndex = try AITopicIndex(url: directory.appendingPathComponent("legacy.sqlite"))
    let legacyImporter = AITopicIndexer(index: legacyIndex, locations: .init(home: legacyHome))
    try legacyImporter.refresh(); try legacyImporter.refresh()
    try check("没有数据库的旧版 Codex 保留标题与正文", try legacyIndex.search("旧版会话可持续检索").topics.first?.title == "旧版会话可持续检索")
    let archive = legacyHome.appendingPathComponent(".codex/archived_sessions")
    try FileManager.default.createDirectory(at: archive, withIntermediateDirectories: true)
    let archivedFile = archive.appendingPathComponent("legacy.jsonl")
    try FileManager.default.moveItem(at: legacyFile, to: archivedFile); try legacyImporter.refresh(); try legacyImporter.refresh()
    try check("旧版日志归档移动撤下搜索结果", try legacyIndex.search("").topics.isEmpty && legacyIndex.search("旧版会话可持续检索").topics.isEmpty && legacyIndex.topic("codex:" + codexID)?.archived == true)
    try FileManager.default.moveItem(at: archivedFile, to: legacyFile); try legacyImporter.refresh()
    try check("旧版日志取消归档恢复正文检索", try legacyIndex.search("旧版会话可持续检索").topics.count == 1)
    try FileManager.default.moveItem(at: legacyFile, to: archivedFile); try legacyImporter.refresh()
    try FileManager.default.removeItem(at: archivedFile); try legacyImporter.refresh()
    try check("旧版 Codex 日志删除同步", try legacyIndex.search("").topics.isEmpty)
    let report: [String:Any] = ["checks":checks,"unchanged_refresh_ms":refreshMS,"append_import_ms":updateMS]
    try JSONSerialization.data(withJSONObject: report, options: [.prettyPrinted,.sortedKeys]).write(to: root.appendingPathComponent("sync-results.json"))
    print("All \(checks.count) synchronization checks passed")
}
